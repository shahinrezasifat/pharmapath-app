def main():
    import sys

    files = sorted(glob.glob("assets/learning/*.json"))
    covered = set()
    count = 0
    for path in files:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        changed = False
        for course in data.get("courses", []):
            for lesson in course.get("lessons", []):
                key = "%s::%s" % (course["id"], lesson["id"])
                quiz = QUIZZES.get(key)
                if quiz is None:
                    continue
                assert len(quiz) == 2, key
                lesson["quiz"] = quiz
                covered.add(key)
                count += 1
                changed = True
        if changed:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
                f.write("\n")
            print("updated", path)
    missing = sorted(set(QUIZZES) - covered)
    if missing:
        sys.exit("Quiz keys with no matching lesson: %s" % missing)
    print("Attached quizzes to %d lessons." % count)


if __name__ == "__main__":
    main()
